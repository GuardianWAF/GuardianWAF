//go:build ignore

// DeepcopyGen generates DeepCopy methods for all struct types in config.go.
package main

import (
	"flag"
	"fmt"
	"go/ast"
	"go/parser"
	"go/printer"
	"go/token"
	"os"
	"path"
	"strconv"
	"strings"
)

func main() {
	complete := flag.Bool("complete", false, "emit a complete Go source file, including package and required imports")
	flag.Parse()
	if flag.NArg() == 0 {
		fmt.Fprintln(os.Stderr, "usage: deepcopy-generator [-complete] source.go [source.go ...]")
		os.Exit(1)
	}
	src := flag.Arg(0)

	fset := token.NewFileSet()
	file, err := parser.ParseFile(fset, src, nil, parser.ParseComments)
	if err != nil {
		fmt.Fprintf(os.Stderr, "parse error: %v\n", err)
		os.Exit(1)
	}
	for _, src := range flag.Args()[1:] {
		extra, err := parser.ParseFile(fset, src, nil, parser.ParseComments)
		if err != nil {
			fmt.Fprintf(os.Stderr, "parse error: %v\n", err)
			os.Exit(1)
		}
		if extra.Name.Name != file.Name.Name {
			fmt.Fprintln(os.Stderr, "all input files must have the same package")
			os.Exit(1)
		}
		file.Decls = append(file.Decls, extra.Decls...)
		file.Imports = append(file.Imports, extra.Imports...)
	}

	structTypes := make(map[string]bool)
	for _, decl := range file.Decls {
		if gen, ok := decl.(*ast.GenDecl); ok && gen.Tok == token.TYPE {
			for _, spec := range gen.Specs {
				ts := spec.(*ast.TypeSpec)
				if st, ok := ts.Type.(*ast.StructType); ok {
					for _, field := range st.Fields.List {
						for _, name := range field.Names {
							if name.Name != "_" {
								structTypes[ts.Name.Name] = true
							}
						}
					}
				}
			}
		}
	}
	var generated []string
	for _, decl := range file.Decls {
		genDecl, ok := decl.(*ast.GenDecl)
		if !ok || genDecl.Tok != token.TYPE {
			continue
		}
		for _, spec := range genDecl.Specs {
			typeSpec, ok := spec.(*ast.TypeSpec)
			if !ok {
				continue
			}
			structType, ok := typeSpec.Type.(*ast.StructType)
			if !ok {
				continue
			}
			method := generateDeepCopy(typeSpec.Name.Name, structType, structTypes)
			if method != "" {
				generated = append(generated, method)
			}
		}
	}

	if *complete {
		fmt.Println("// Code generated by tools/deepcopy; DO NOT EDIT.")
		fmt.Printf("package %s\n\n", file.Name.Name)
		// Scalar assignments do not name their types. Inspect the emitted code
		// so only imports referenced by allocations and type literals remain.
		used := make(map[string]bool)
		output, err := parser.ParseFile(token.NewFileSet(), "generated.go", "package "+file.Name.Name+"\n"+strings.Join(generated, "\n"), 0)
		if err != nil {
			fmt.Fprintf(os.Stderr, "generated source: %v\n", err)
			os.Exit(1)
		}
		ast.Inspect(output, func(n ast.Node) bool {
			if sel, ok := n.(*ast.SelectorExpr); ok {
				if id, ok := sel.X.(*ast.Ident); ok {
					used[id.Name] = true
				}
			}
			return true
		})
		emitted := make(map[string]bool)
		for _, imp := range file.Imports {
			value, _ := strconv.Unquote(imp.Path.Value)
			name := path.Base(value)
			if imp.Name != nil {
				name = imp.Name.Name
			}
			if used[name] && !emitted[name+imp.Path.Value] {
				fmt.Printf("import %s %s\n", name, imp.Path.Value)
				emitted[name+imp.Path.Value] = true
			}
		}
	}
	for _, g := range generated {
		fmt.Println(g)
	}
}

func generateDeepCopy(typeName string, st *ast.StructType, structTypes map[string]bool) string {
	var fields []fieldInfo
	for _, field := range st.Fields.List {
		if field.Names == nil {
			continue
		}
		for _, name := range field.Names {
			if name.Name == "_" {
				continue
			}
			fields = append(fields, fieldInfo{name: name.Name, typ: field.Type})
		}
	}

	if len(fields) == 0 {
		return ""
	}

	var bodyLines []string
	bodyLines = append(bodyLines, fmt.Sprintf("func (in *%s) DeepCopy() *%s {", typeName, typeName))
	bodyLines = append(bodyLines, "\tif in == nil {")
	bodyLines = append(bodyLines, "\t\treturn nil")
	bodyLines = append(bodyLines, "\t}")
	bodyLines = append(bodyLines, "\tout := *in // shallow copy of scalar fields")

	for _, f := range fields {
		for _, line := range copyLines("out."+f.name, "in."+f.name, f.typ, structTypes, 0) {
			bodyLines = append(bodyLines, "\t"+line)
		}
	}

	bodyLines = append(bodyLines, "\treturn &out")
	bodyLines = append(bodyLines, "}")

	return strings.Join(bodyLines, "\n")
}

type fieldInfo struct {
	name string
	typ  ast.Expr
}

func typeString(e ast.Expr) string {
	var b strings.Builder
	_ = printer.Fprint(&b, token.NewFileSet(), e)
	return b.String()
}

func copyLines(dst, src string, typ ast.Expr, structTypes map[string]bool, depth int) []string {
	indent := func(lines []string) []string {
		for i := range lines {
			lines[i] = "\t" + lines[i]
		}
		return lines
	}
	switch t := typ.(type) {
	case *ast.StarExpr:
		lines := []string{fmt.Sprintf("if %s != nil {", src), fmt.Sprintf("\t%s = new(%s)", dst, typeString(t.X))}
		lines = append(lines, indent(copyLines("*("+dst+")", "*("+src+")", t.X, structTypes, depth+1))...)
		return append(lines, "}")
	case *ast.ArrayType:
		var lines []string
		if t.Len == nil {
			lines = append(lines, fmt.Sprintf("if %s != nil {", src), fmt.Sprintf("\t%s = make(%s, len(%s))", dst, typeString(t), src))
		}
		idx := fmt.Sprintf("i%d", depth)
		loop := []string{fmt.Sprintf("for %s := range %s {", idx, src)}
		loop = append(loop, indent(copyLines(fmt.Sprintf("(%s)[%s]", dst, idx), fmt.Sprintf("(%s)[%s]", src, idx), t.Elt, structTypes, depth+1))...)
		loop = append(loop, "}")
		if t.Len == nil {
			lines = append(lines, indent(loop)...)
			return append(lines, "}")
		}
		return loop
	case *ast.MapType:
		key, value, copied := fmt.Sprintf("k%d", depth), fmt.Sprintf("v%d", depth), fmt.Sprintf("copy%d", depth)
		lines := []string{fmt.Sprintf("if %s != nil {", src), fmt.Sprintf("\t%s = make(%s, len(%s))", dst, typeString(t), src), fmt.Sprintf("\tfor %s, %s := range %s {", key, value, src), fmt.Sprintf("\t\t%s := %s", copied, value)}
		lines = append(lines, indent(indent(copyLines(copied, value, t.Value, structTypes, depth+1)))...)
		return append(lines, fmt.Sprintf("\t\t(%s)[%s] = %s", dst, key, copied), "\t}", "}")
	case *ast.Ident:
		if t.Name == "any" {
			// Config condition values allow either scalar values or lists.
			// The interface's shallow assignment does not own those lists.
			value := fmt.Sprintf("value%d", depth)
			copied := fmt.Sprintf("list%d", depth)
			lines := []string{fmt.Sprintf("switch %s := %s.(type) {", value, src)}
			for _, typ := range []string{"[]string", "[]any"} {
				lines = append(lines, "case "+typ+":", fmt.Sprintf("\tif %s != nil {", value), fmt.Sprintf("\t\t%s := make(%s, len(%s))", copied, typ, value), fmt.Sprintf("\t\tcopy(%s, %s)", copied, value), fmt.Sprintf("\t\t%s = %s", dst, copied), "\t}")
			}
			return append(lines, "}")
		}
		if structTypes[t.Name] {
			return []string{fmt.Sprintf("%s = *((%s).DeepCopy())", dst, src)}
		}
	}
	return []string{fmt.Sprintf("%s = %s", dst, src)}
}
