func (a *mcpEngineAdapter) GetCRSRules(phase int, severity string) (any, error) {
	layer := a.engine.FindLayer("crs")
	if layer == nil {
		return map[string]any{"enabled": false, "rules": []any{}}, nil
	}
	crsLayer, ok := layer.(*crs.Layer)
	if !ok {
		return map[string]any{"enabled": a.cfg.WAF.CRS.Enabled, "rules": []any{}}, nil
	}
	var rules []*crs.Rule
	if phase > 0 {
		rules = crsLayer.GetRulesByPhase(phase)
	} else {
		rules = crsLayer.GetAllRules()
	}
	filtered := make([]map[string]any, 0, len(rules))
	for _, r := range rules {
		info := map[string]any{
			"id":      r.ID,
			"phase":   r.Phase,
			"enabled": crsLayer.IsRuleEnabled(r.ID),
		}
		if severity != "" && r.Severity != severity {
			continue
		}
		filtered = append(filtered, info)
	}
	return map[string]any{
		"enabled": a.cfg.WAF.CRS.Enabled,
		"rules":   filtered,
	}, nil
}

func (a *mcpEngineAdapter) EnableCRSRule(ruleID string, enabled bool) error {
	layer := a.engine.FindLayer("crs")
	if layer == nil {
		return fmt.Errorf("CRS layer not available")
	}
	crsLayer, ok := layer.(*crs.Layer)
	if !ok {
		return fmt.Errorf("CRS layer type mismatch")
	}
	// crs.Layer.EnableRule/DisableRule are void and DisableRule records
	// disabledRules state for ANY id — an unknown or typo'd rule ID must
	// error here, not report success (same contract as the dashboard's CRS
	// toggle, bug-hunt round 15).
	if crsLayer.GetRule(ruleID) == nil {
		return fmt.Errorf("CRS rule %q not found", ruleID)
	}
	if enabled {
		crsLayer.EnableRule(ruleID)
	} else {
		crsLayer.DisableRule(ruleID)
	}
	return nil
}

