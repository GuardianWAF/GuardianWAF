func (a *mcpEngineAdapter) GetAPISchemas() (any, error) {
	layer := a.engine.FindLayer("apivalidation")
	if layer == nil {
		return map[string]any{"enabled": false, "schemas": []any{}}, nil
	}
	apiLayer, ok := layer.(*apivalidation.Layer)
	if !ok {
		return map[string]any{"enabled": a.cfg.WAF.APIValidation.Enabled, "schemas": []any{}}, nil
	}
	specs := apiLayer.GetSpecs()
	schemaList := make([]map[string]any, 0, len(specs))
	for _, spec := range specs {
		schemaList = append(schemaList, map[string]any{
			"path":       spec.Source.Path,
			"type":       spec.Source.Type,
			"auto_learn": spec.Source.AutoLearn,
		})
	}
	return map[string]any{
		"enabled": a.cfg.WAF.APIValidation.Enabled,
		"schemas": schemaList,
	}, nil
}

func (a *mcpEngineAdapter) UploadAPISchema(name, content, format string, strictMode bool) error {
	layer := a.engine.FindLayer("apivalidation")
	if layer == nil {
		return fmt.Errorf("API validation layer not available")
	}
	apiLayer, ok := layer.(*apivalidation.Layer)
	if !ok {
		return fmt.Errorf("API validation layer type mismatch")
	}
	if name == "" {
		return fmt.Errorf("schema name is required")
	}
	if content == "" {
		return fmt.Errorf("schema content is required")
	}

	schemaType := strings.ToLower(format)
	if schemaType == "" || schemaType == "json" {
		schemaType = "jsonschema"
	}

	// Inline content: no filesystem staging — uploads are CWD-independent
	// and never interact with the working-directory confinement in the
	// layer's readFile. strictMode has no per-schema counterpart in the
	// layer (it is a global config flag).
	return apiLayer.LoadSchema(apivalidation.SchemaSource{
		Type:    schemaType,
		Content: content,
		Name:    name,
	})
}

