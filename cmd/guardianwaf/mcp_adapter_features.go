func (a *mcpEngineAdapter) AddDLPPattern(id, name, pattern, description, action string, score int) error {
	layer := a.engine.FindLayer("dlp")
	if layer == nil {
		return fmt.Errorf("DLP layer not available")
	}
	dlpLayer, ok := layer.(*dlp.Layer)
	if !ok {
		return fmt.Errorf("DLP layer type mismatch")
	}
	re, err := regexp.Compile(pattern)
	if err != nil {
		return fmt.Errorf("invalid regex pattern: %w", err)
	}
	severity := dlp.SeverityMedium
	switch action {
	case "block":
		severity = dlp.SeverityHigh
	case "log":
		severity = dlp.SeverityLow
	}
	dlpLayer.AddCustomPattern(id, &dlp.Pattern{
		Type:       dlp.PatternCustom,
		Name:       name,
		Regex:      re,
		Severity:   severity,
		Enabled:    true,
		MaskFormat: "***MASKED***",
	})
	return nil
}

func (a *mcpEngineAdapter) RemoveDLPPattern(id string) error {
	layer := a.engine.FindLayer("dlp")
	if layer == nil {
		return fmt.Errorf("DLP layer not available")
	}
	dlpLayer, ok := layer.(*dlp.Layer)
	if !ok {
		return fmt.Errorf("DLP layer type mismatch")
	}
	registry := dlpLayer.GetRegistry()
	if !registry.RemoveCustomPattern(id) {
		return fmt.Errorf("DLP pattern %q not found", id)
	}
	return nil
}

func (a *mcpEngineAdapter) TestDLPPattern(pattern, testData string) (any, error) {
	re, err := regexp.Compile(pattern)
	if err != nil {
		return map[string]any{"error": fmt.Sprintf("invalid regex: %v", err)}, nil
	}
	matches := re.FindAllString(testData, -1)
	return map[string]any{
		"matched": len(matches) > 0,
		"matches": matches,
	}, nil
}

