func (a *mcpEngineAdapter) AddCRSExclusion(ruleID, path, parameter, reason string) error {
	layer := a.engine.FindLayer("crs")
	if layer == nil {
		return fmt.Errorf("CRS layer not available")
	}
	crsLayer, ok := layer.(*crs.Layer)
	if !ok {
		return fmt.Errorf("CRS layer type mismatch")
	}
	// Same toggle contract as EnableCRSRule above (new-series round 3, and
	// the dashboard's CRS toggle in the prior series' round 15): an unknown
	// or typo'd rule ID must error here, not fake success — DisableRule
	// records phantom disabledRules state for any id, and the raw ID would
	// persist in cfg.WAF.CRS.DisabledRules across reloads.
	if crsLayer.GetRule(ruleID) == nil {
		return fmt.Errorf("CRS rule %q not found", ruleID)
	}
	// Track the layer-side state this call mutates: the persistence rollback
	// below reloads the config but cannot undo DisableRule (layer-internal
	// state), so it is reverted explicitly when persistence fails.
	wasEnabled := crsLayer.IsRuleEnabled(ruleID)
	crsLayer.DisableRule(ruleID)
	oldCfg := a.engine.Config()
	cfg := a.engine.Config()
	cfg.WAF.CRS.DisabledRules = append(cfg.WAF.CRS.DisabledRules, ruleID)
	if err := a.engine.Reload(cfg); err != nil {
		return err
	}
	if err := a.persistConfig(oldCfg); err != nil {
		if wasEnabled {
			crsLayer.EnableRule(ruleID)
		}
		return err
	}
	return nil
}

func (a *mcpEngineAdapter) GetVirtualPatches(severity string, activeOnly bool) (any, error) {
	layer := a.engine.FindLayer("virtualpatch")
	if layer == nil {
		return map[string]any{"enabled": false, "patches": []any{}}, nil
	}
	vpLayer, ok := layer.(*virtualpatch.Layer)
	if !ok {
		return map[string]any{"enabled": a.cfg.WAF.VirtualPatch.Enabled, "patches": []any{}}, nil
	}
	var patches []virtualpatch.VirtualPatch
	if activeOnly {
		patches = vpLayer.GetActivePatches()
	} else {
		patches = vpLayer.GetAllPatches()
	}
	filtered := make([]map[string]any, 0, len(patches))
	for _, p := range patches {
		if severity != "" && p.Severity != severity {
			continue
		}
		filtered = append(filtered, map[string]any{
			"id":             p.ID,
			"cve_id":         p.CVEID,
			"name":           p.Name,
			"severity":       p.Severity,
			"action":         p.Action,
			"score":          p.Score,
			"enabled":        p.Enabled,
			"hits":           p.Hits,
			"auto_generated": p.AutoGenerated,
			"review_status":  p.ReviewStatus,
			"provenance":     p.Provenance,
			"reviewed_by":    p.ReviewedBy,
			"applied_by":     p.AppliedBy,
		})
	}
	return map[string]any{
		"enabled": a.cfg.WAF.VirtualPatch.Enabled,
		"patches": filtered,
	}, nil
}

func (a *mcpEngineAdapter) EnableVirtualPatch(patchID string, enabled bool) error {
	layer := a.engine.FindLayer("virtualpatch")
	if layer == nil {
		return fmt.Errorf("virtual patch layer not available")
	}
	vpLayer, ok := layer.(*virtualpatch.Layer)
	if !ok {
		return fmt.Errorf("virtual patch layer type mismatch")
	}
	if enabled {
		if !vpLayer.EnablePatchBy(patchID, "mcp") {
			return fmt.Errorf("patch %q not found", patchID)
		}
	} else {
		if !vpLayer.DisablePatchBy(patchID, "mcp") {
			return fmt.Errorf("patch %q not found", patchID)
		}
	}
	return nil
}

func (a *mcpEngineAdapter) AddCustomPatch(id, name, description, cveID, pattern, patternType, target, action, severity string, score int) error {
	layer := a.engine.FindLayer("virtualpatch")
	if layer == nil {
		return fmt.Errorf("virtual patch layer not available")
	}
	vpLayer, ok := layer.(*virtualpatch.Layer)
	if !ok {
		return fmt.Errorf("virtual patch layer type mismatch")
	}
	patch := &virtualpatch.VirtualPatch{
		ID:          id,
		CVEID:       cveID,
		Name:        name,
		Description: description,
		GeneratedAt: time.Now(),
		Patterns: []virtualpatch.PatchPattern{
			{
				Type:      target,
				Pattern:   pattern,
				MatchType: patternType,
			},
		},
		Action:        action,
		Score:         score,
		Severity:      severity,
		Enabled:       true,
		AutoGenerated: false,
		Provenance:    "mcp:manual",
	}
	vpLayer.AddPatch(patch)
	return nil
}

